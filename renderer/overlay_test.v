fn test_overlay_rectangle_matches_z2d_0_10_fill_and_hairline_bytes() {
	mut overlay := overlay_for_grid(6, 6, 1, 1)
	overlay.highlight_grid_rect(1, 1, 3, 3, .hyperlink)!

	// Generated by the pinned z2d Surface/Context path used by Overlay.zig:
	// fill with AA disabled, followed by a closed hairline stroke.
	mut alpha := []u8{cap: 36}
	for y in 0 .. 6 {
		for x in 0 .. 6 {
			alpha << overlay_pixel(&overlay, x, y)[3]
		}
	}
	assert alpha == [u8(0), 0, 0, 0, 0, 0, 0, 248, 221, 221, 244, 0, 0, 221, 96, 96, 200, 0, 0,
		221, 96, 96, 200, 0, 0, 244, 200, 200, 244, 0, 0, 0, 0, 0, 0, 0]
	assert overlay_pixel(&overlay, 1, 1) == [u8(174), 174, 247, 248]!
	assert overlay_pixel(&overlay, 2, 1) == [u8(155), 155, 220, 221]!
	assert overlay_pixel(&overlay, 4, 1) == [u8(171), 171, 243, 244]!
	assert overlay_pixel(&overlay, 2, 2) == [u8(67), 67, 96, 96]!
	assert overlay_pixel(&overlay, 4, 2) == [u8(141), 141, 200, 200]!
	assert sha256.sum(overlay.pending_image().data).hex() == '5ebe13c89b22bd043a617cd62763811ceb2a8f60b4687e1244a088d11d277f30'
}

fn test_overlay_degenerate_rectangles_match_z2d_0_10_bytes() {
	mut overlay := overlay_for_grid(6, 6, 1, 1)
	overlay.highlight_pixel_rect(1, 1, 0, 3, .hyperlink)!
	assert sha256.sum(overlay.pending_image().data).hex() == '509c9cfe914dc7b2427c70b16489052b0e79194f1bc8e9e8936c15c3e2c4a035'

	overlay.reset()
	overlay.highlight_pixel_rect(1, 1, 3, 0, .hyperlink)!
	assert sha256.sum(overlay.pending_image().data).hex() == 'd511718883dcefd72d324c6991efeaaed8df6b64fe6e1dfc5f163347b69a3aa3'

	overlay.reset()
	overlay.highlight_pixel_rect(1, 1, 0, 0, .hyperlink)!
	assert sha256.sum(overlay.pending_image().data).hex() == '451f2e215103f9c5934940c07f448cec6a3221a94d77d25b810e16eaad6bdac2'
}

fn test_overlay_clips_large_rectangles_to_the_canvas() ! {
	mut overlay := overlay_for_grid(3, 3, 1, 1)
	overlay.highlight_pixel_rect(1, 1, overlay_max_i32, overlay_max_i32, .hyperlink)!
	assert overlay_pixel(&overlay, 0, 0) == [u8(0), 0, 0, 0]!
	assert overlay_pixel(&overlay, 2, 2) == [u8(67), 67, 96, 96]!
	assert overlay_pixel(&overlay, 1, 1) == [u8(174), 174, 247, 248]!
}

fn overlay_for_grid(cols u32, rows u32, cell_width u32, cell_height u32) Overlay {
	return Overlay.init(Size{
		screen: ScreenSize{
			width:  cols * cell_width
			height: rows * cell_height
		}
		cell:   CellSize{
			width:  cell_width
			height: cell_height
		}
	}) or { panic(err) }
}

fn overlay_pixel(overlay &Overlay, x int, y int) [4]u8 {
	pixel := overlay.surface.pixels[y * overlay.surface.width + x]
	return [u8(pixel >> 16), u8(pixel >> 8), u8(pixel), u8(pixel >> 24)]!
}

fn test_overlay_rejects_dimensions_outside_source_raster_range() {
	Overlay.init(Size{
		screen: ScreenSize{
			width:  u32(2147483648)
			height: 1
		}
	}) or {
		assert err.msg() == 'invalid dimensions for overlay'
		return
	}
	assert false, 'out-of-range overlay width should fail'
}

fn test_overlay_grid_rectangle_rejects_coordinate_overflow() {
	mut overlay := overlay_for_grid(1, 1, 1, 1)
	overlay.cell_size.width = 2
	overlay.highlight_grid_rect(uint(2147483647), 0, 1, 1, .hyperlink) or {
		assert err.msg() == 'overlay coordinate overflow'
		assert overlay.surface.pixels == [u32(0)]
		return
	}
	assert false, 'out-of-range overlay coordinate should fail'
}

fn render_cell_with_hyperlink(active bool) terminal.RenderCell {
	return terminal.RenderCell{
		raw: terminal.CellData{
			has_hyperlink: active
		}
	}
}

fn test_overlay_highlights_contiguous_hyperlink_runs() {
	mut overlay := overlay_for_grid(4, 1, 10, 10)
	state := terminal.RenderState{
		row_data: [terminal.RenderRow{
			raw:   terminal.RowData{
				header: &terminal.PageRowHeader{ hyperlink: true }
			}
			cells: [render_cell_with_hyperlink(false), render_cell_with_hyperlink(true),
				render_cell_with_hyperlink(true), render_cell_with_hyperlink(false)]
		}]
	}
	overlay.apply_features(&state, [.highlight_hyperlinks])

	assert overlay_pixel(&overlay, 5, 5)[3] == 0
	assert overlay_pixel(&overlay, 15, 5)[3] == 96
	assert overlay_pixel(&overlay, 25, 5)[3] == 96
	assert overlay_pixel(&overlay, 35, 5)[3] == 0
	assert overlay_pixel(&overlay, 10, 5)[3] == 221
	// z2d surfaces are premultiplied RGBA.
	assert overlay_pixel(&overlay, 15, 5)[0] == 67
}

fn test_overlay_joins_semantic_prompt_continuation_bars() {
	mut overlay := overlay_for_grid(2, 3, 10, 10)
	state := terminal.RenderState{
		row_data: [
			terminal.RenderRow{
				raw: terminal.RowData{
					header: &terminal.PageRowHeader{ semantic_prompt: .prompt }
				}
			},
			terminal.RenderRow{
				raw: terminal.RowData{
					header: &terminal.PageRowHeader{ semantic_prompt: .prompt_continuation }
				}
			},
			terminal.RenderRow{
				raw: terminal.RowData{
					header: &terminal.PageRowHeader{ semantic_prompt: .unknown }
				}
			},
		]
	}
	overlay.apply_features(&state, [.semantic_prompts])

	assert overlay_pixel(&overlay, 2, 5)[3] == 96
	assert overlay_pixel(&overlay, 2, 15)[3] == 96
	assert overlay_pixel(&overlay, 2, 25)[3] == 0
}

fn semantic_render_cell(content terminal.SemanticContent) terminal.RenderCell {
	return terminal.RenderCell{
		raw: terminal.CellData{
			semantic_content: content
		}
	}
}

fn test_overlay_highlights_semantic_cells_but_skips_output() {
	mut overlay := overlay_for_grid(4, 1, 10, 10)
	state := terminal.RenderState{
		row_data: [terminal.RenderRow{
			cells: [semantic_render_cell(.output), semantic_render_cell(.prompt),
				semantic_render_cell(.prompt), semantic_render_cell(.input)]
		}]
	}
	overlay.apply_features(&state, [.semantic_prompts])

	assert overlay_pixel(&overlay, 5, 5)[3] == 0
	assert overlay_pixel(&overlay, 15, 5)[3] == 96
	assert overlay_pixel(&overlay, 25, 5)[3] == 96
	assert overlay_pixel(&overlay, 35, 5)[3] == 96
	// Prompt and input use distinct colors.
	assert overlay_pixel(&overlay, 15, 5) != overlay_pixel(&overlay, 35, 5)
}
